/* Traffic light per test: G / Y / R */
var CARD_TESTS = [
  { k: "g", l: "צמיחה", f: function (v) { return v == null ? "R" : v >= 10 ? "G" : v >= 5 ? "Y" : "R"; }, v: function (v) { return v == null ? "אין הכנסות" : (v > 0 ? "+" : "") + v + "%"; } },
  { k: "fcf", l: "תזרים חופשי", f: function (v) { return v == null ? "R" : v >= 8 ? "G" : v >= 0 ? "Y" : "R"; }, v: function (v) { return v == null ? "שלילי" : "~" + v + "%"; } },
  { k: "roic", l: "תשואה על ההון", f: function (v) { return v == null ? "R" : v >= 15 ? "G" : v >= 8 ? "Y" : "R"; }, v: function (v) { return v == null ? "שלילית" : "~" + v + "%"; } },
  { k: "pe", l: "מכפיל רווח", f: function (v) { return v == null ? "R" : v < 20 ? "G" : v < 35 ? "Y" : "R"; }, v: function (v) { return v == null ? "אין רווח" : v >= 200 ? "200+" : "~" + v; } }
];

/* An ETF (etf: true) has no company reports: no verdict; its card shows facts: [[label, value]] instead of the tests.
   A test value of "na" (e.g. free cash flow for a bank) is shown grey and left out; points are scaled to 4 tests.
   Score: green 2, yellow 1, red 0 (max 8).
   7+ and no warning: strong candidate. 6+: worth researching (so no opportunity is lost).
   4-5: borderline. Below 4: not now. */
function cardVerdict(c) {
  if (c.etf) return { lights: ["N", "N", "N", "N"], cls: "N", label: c.lbl || "קרן סל", greens: 0 };
  var L = CARD_TESTS.map(function (t) { return c[t.k] === "na" ? "N" : t.f(c[t.k]); });
  var n = L.filter(function (x) { return x !== "N"; }).length || 1;
  var pts = L.reduce(function (a, x) { return a + (x === "G" ? 2 : x === "Y" ? 1 : 0); }, 0) * 4 / n;
  var warned = (c.warn || []).length > 0;
  var v = (pts >= 7 && !warned) ? ["S", "מועמדת חזקה"] : pts >= 6 ? ["G", "שווה לחקור"] : pts >= 4 ? ["Y", "גבולי"] : ["R", "לא עכשיו"];
  return { lights: L, cls: v[0], label: v[1], greens: L.filter(function (x) { return x === "G"; }).length };
}
